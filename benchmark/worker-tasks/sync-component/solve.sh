#!/usr/bin/env bash
# Reference run: read origin/main only (the checkout is behind and dirty), write the inventory.
source "$TASK_DIR/../lib.sh"

repo=repos/billing-gitops
git -C "$repo" fetch -q origin
sha=$(git -C "$repo" rev-parse --short=7 origin/main)
committed=$(git -C "$repo" log -1 --format=%cd --date=format:%d.%m.%Y origin/main)
show() { git -C "$repo" show "origin/main:$1"; }
yaml_key() { awk -v key="$1" '$1 == key":" { print $2; exit }' | tr -d '"'; }

inventory=infra/acme/billing/inventory.md
{
	printf '# billing (acme) inventory\n\nGenerated by the `sync-component` workbook from `origin/main` of the component repo. Do not hand-edit.\n\n'
	printf '## Source\n- Repo `%s`, `origin/main` %s, committed %s\n\n' "$repo" "$sha" "$committed"
	printf '## Applications\n| App | Stage | Namespace | Chart | Version |\n|-----|-------|-----------|-------|---------|\n'
	git -C "$repo" ls-tree -r --name-only origin/main apps/ | grep -E '^apps/[^/]+/values-[a-z]+\.yaml$' | LC_ALL=C sort | while read -r path; do
		app=$(echo "$path" | cut -d/ -f2)
		stage=$(basename "$path" .yaml)
		stage=${stage#values-}
		printf '| %s | %s | %s | %s | %s |\n' "$app" "$stage" "$(show "$path" | yaml_key namespace)" \
			"$(show "apps/$app/Chart.yaml" | yaml_key name)" "$(show "apps/$app/Chart.yaml" | yaml_key version)"
	done
	printf '\n## Open items\n'
	show TODO.md | grep '^- '
} >"$inventory"

run_day=$(date -u +%d.%m.%Y)
report="journal/runs/$(date -u +%F)-sync-component-billing-inventory.md"
journal="journal/$(date -u +%Y-%m).md"
cat >"$report" <<EOF
---
date: $run_day
workbook: sync-component
component: acme/billing
outcome: done
duration: 10 min
---

## Task
Synced acme/billing at origin/main $sha: dunning-mailer added (staging), invoice-api 1.8.0 -> 1.9.0. Local checkout was behind and dirty (billing-db Chart.yaml), not used.

## What went wrong on first try
- none

## Instructions that were wrong or missing
- none

## Missing access
- none

## Tool / environment friction
- none

## Suggested improvements
- none
EOF
echo "- $run_day acme/billing: sync-component billing-inventory - done; inventory at $sha; run report $report" >>"$journal"
finish_worker "docs(infra): sync acme/billing at $sha" "$inventory" "$report" "$journal"
